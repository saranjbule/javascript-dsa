/**
 * Binary Tree:
 * - hierarchical data structure
 * - at max a node can have 2 childrens (0, 1, 2)
 *
 * Tree terminology
 * - root | childrens | siblings | sub-tree | ancestors | leaf
 *
 * Types of Binary Tree
 *
 * - Full Binary Tree
 *   - a node has 0 or 2 childrens
 *
 * - Complete Binary Tree
 *   - all levels of tree are completely filled except the last level
 *   - if last level is not completely filled, then last level has all nodes in left
 *
 * - Perfect Binary tree
 *   - all leaf nodes need to be at same level
 *
 * - Balanced Binary Tree
 *   - height of tree is at max log(N) (N is number of node)
 *
 * - Degenerate Tree | Skew Tree
 *   - every node has single children
 */
