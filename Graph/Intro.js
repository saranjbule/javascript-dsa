/**
 * Category of Graphs
 * 1. Directed (-> | <-)
 * 2. Undirected (-)
 *
 * Terminology
 * - node / vertex
 *
 * - edge
 *   - directed edge
 *   - undirected edge
 *   - weighted edge
 *
 * - cyclic graph : start from a node N and end on node N
 *
 * - acyclic graph : Reverse of cyclic
 *
 * - path : a node cannot appear twice in a path,
 *          each node is traverse just once and
 *          adjacent node must have connecting edge between them
 *
 * - In an Undirected Graph
 *   - degree : number of edges connected of a node
 *     - Total degree of a undirected graph = 2 * ( Number of Edges ) | every node is connected with 2 nodes
 * 
 * - In Directed Graph
 *   - In degree : number of incoming edges
 *   - Out degree : number of outgoing edges
 */
